#!/usr/bin/env node
/** Generate the native-only bridge from the same tokens/Lucide nodes as React. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const tokens = require('../src/design-tokens.json');
const output = path.join(root, 'modules/recallbox-callback/android/src/main/res');
const check = process.argv.includes('--check');
let drift = false;
function write(relative, value) {
  const file = path.join(output, relative);
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== value) {console.error(`Stale native design resource: ${relative}`); drift = true;}
  } else {fs.mkdirSync(path.dirname(file), {recursive: true}); fs.writeFileSync(file, value);}
}
const snake = text => text.replace(/[A-Z]/g, x => '_' + x.toLowerCase());
const escape = text => String(text).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
function androidColor(value) {
  if (!value.startsWith('rgba')) return value;
  const [r, g, b, a] = value.match(/[\d.]+/g).map(Number);
  return '#' + [Math.round(a * 255), r, g, b].map(v => v.toString(16).padStart(2, '0')).join('');
}
for (const mode of ['light', 'dark']) {
  const colors = Object.entries(tokens.colors[mode]).map(([name, value]) => `  <color name="recallbox_${snake(name)}">${androidColor(value)}</color>`);
  colors.push('  <color name="recallbox_share_brand">@color/recallbox_brand</color>', '  <color name="recallbox_share_on_brand">@color/recallbox_on_brand</color>');
  write(`${mode === 'dark' ? 'values-night' : 'values'}/colors.xml`, `<!-- Generated by npm run design:sync. Edit src/design-tokens.json. -->\n<resources>\n${colors.join('\n')}\n</resources>\n`);
}
const dimensions = [];
for (const [name, value] of Object.entries(tokens.spacing)) dimensions.push(`  <dimen name="recallbox_space_${snake(name)}">${value}dp</dimen>`);
for (const [name, value] of Object.entries(tokens.radii)) dimensions.push(`  <dimen name="recallbox_radius_${snake(name)}">${value}dp</dimen>`);
for (const [name, value] of Object.entries(tokens.geometry)) dimensions.push(`  <dimen name="recallbox_${snake(name)}">${value}dp</dimen>`);
for (const [name, value] of Object.entries(tokens.typography)) dimensions.push(`  <dimen name="recallbox_type_${snake(name)}">${value.fontSize}sp</dimen>`);
for (const [name, value] of Object.entries(tokens.elevation)) dimensions.push(`  <dimen name="recallbox_elevation_${name}">${value.elevation}dp</dimen>`);
write('values/recallbox_design.xml', `<!-- Generated by npm run design:sync. -->\n<resources>\n${dimensions.join('\n')}\n</resources>\n`);
const iconRoot = path.join(root, 'node_modules/lucide-react-native/dist/esm/icons');
function iconData(name) {
  const code = fs.readFileSync(path.join(iconRoot, `${name}.mjs`), 'utf8');
  const alias = /export \{ default \} from '\.\/(.+)\.mjs'/.exec(code);
  if (alias) return iconData(alias[1]);
  const match = /const __iconData = (\{[\s\S]*?\n\});/.exec(code);
  if (!match) throw new Error(`Unsupported Lucide data format: ${name}`);
  // This evaluates only an object literal from the installed, pinned icon package.
  return vm.runInNewContext('(' + match[1] + ')', {}, {timeout: 1000});
}
for (const name of ['check', 'triangle-alert', 'clock', 'upload']) {
  const data = iconData(name);
  const paths = data.node.map(([shape, attr]) => {
    let d = attr.d;
    if (shape === 'circle') {
      const cx = +attr.cx, cy = +attr.cy, r = +attr.r;
      d = `M${cx-r},${cy} a${r},${r} 0,1 0,${2*r},0 a${r},${r} 0,1 0,-${2*r},0`;
    } else if (shape !== 'path') throw new Error(`Unsupported native icon shape: ${shape}`);
    return `  <path android:pathData="${escape(d)}" android:fillColor="@android:color/transparent" android:strokeColor="@android:color/black" android:strokeWidth="${tokens.geometry.strokeWidth}" android:strokeLineCap="round" android:strokeLineJoin="round"/>`;
  });
  write(`drawable/recallbox_icon_${name.replaceAll('-', '_')}.xml`, `<!-- Generated from Lucide ${name}; license: design-system-NOTICE.txt. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="${data.size}" android:viewportHeight="${data.size}">\n${paths.join('\n')}\n</vector>\n`);
}
const license = fs.readFileSync(path.join(root, 'node_modules/lucide-react-native/LICENSE'), 'utf8');
const notice = path.join(root, 'modules/recallbox-callback/android/src/main/assets/design-system-NOTICE.txt');
if (check) {
  if (!fs.existsSync(notice) || fs.readFileSync(notice, 'utf8') !== license) {console.error('Stale native Lucide license'); drift = true;}
} else {fs.mkdirSync(path.dirname(notice), {recursive: true}); fs.writeFileSync(notice, license);}
if (drift) process.exitCode = 1;
else console.log(check ? 'Native design tokens and Lucide assets match.' : 'Generated native design tokens and Lucide assets.');
